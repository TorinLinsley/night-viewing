pub fn tr(lang: Lang, s: &str) -> String {
    if s == "Night Viewing" {
        return app_name(lang).to_string();
    }
    let i = lang.idx();
    if i == 0 {
        return s.to_string();
    }
    let p = &LANGS[i];
    if let Some(k) = KEYS.iter().position(|x| *x == s) {
        return p.rows[k].to_string();
    }
    if let Some(rest) = s.strip_prefix("亮度 ≈ ") {
        return format!("{}{rest}", p.bright);
    }
    if let Some(rest) = s.strip_prefix("显示器 ") {
        if !rest.is_empty() && rest.bytes().all(|b| b.is_ascii_digit()) {
            return format!("{}{rest}", p.display);
        }
    }
    if let Some(rest) = s.strip_prefix("遮罩 ") {
        return format!("{}{rest}", p.dim);
    }
    s.to_string()
}

